def task_guidance_blocks(
    tool_names: Collection[str], *, domain_policies: Collection[str] = (),
) -> dict[str, str]:
    """Stable keys let the loop append each activated instruction only once."""
    names = set(tool_names)
    blocks = {
        group: text for group, text in _GUIDANCE.items()
        if names & CAPABILITY_GROUPS[group]
    }
    # External providers (MCP/SSH/LSP) do not belong to built-in groups.
    # All work receives the same verification contract regardless of transport.
    if names - {"capability_load", "ask_user", "workflow_request"}:
        blocks = {"work": _WORK_GUIDANCE, **blocks}
    for domain in domain_policies:
        if domain in _DOMAIN_GUIDANCE:
            blocks[domain] = _DOMAIN_GUIDANCE[domain]
    return blocks
